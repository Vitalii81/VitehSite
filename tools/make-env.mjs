// Generates a small studio environment map (equirectangular Radiance HDR, RGBE with run-length encoding): soft boxes on a dark room.
//   node tools/make-env.mjs  ->  assets/env/studio.hdr  (about 256x128). Created by this script, no third-party image: public domain / same licence as the site.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const W = 256, H = 128;
const smooth = (a, b, x) => { const t = Math.min(Math.max((x - a) / (b - a), 0), 1); return t * t * (3 - 2 * t); };
const rad = (d) => (d * Math.PI) / 180;

// soft boxes: azimuth/elevation of the centre (degrees), angular half-size, intensity, colour
const LIGHTS = [
  { az: -35, el: 42, w: 28, h: 20, k: 5.5, c: [1.0, 0.96, 0.9] },     // key: large, warm, upper left
  { az: 105, el: 18, w: 34, h: 26, k: 1.7, c: [0.88, 0.94, 1.0] },    // fill: cool, right
  { az: 180, el: 34, w: 60, h: 7, k: 4.2, c: [1.0, 1.0, 1.0] },       // rim strip behind
  { az: 0, el: 82, w: 38, h: 38, k: 1.4, c: [1.0, 1.0, 1.0] },        // top
  { az: -150, el: 8, w: 18, h: 12, k: 1.1, c: [1.0, 0.9, 0.8] },      // warm kicker
];

function radiance(az, el) {                          // degrees; el > 0 looks up
  const sky = 0.16 + 0.12 * smooth(-10, 70, el), floor = 0.07 + 0.03 * smooth(-80, -5, el);
  let base = el >= 0 ? sky : floor;
  const px = [base * 0.96, base, base * 0.98];
  for (const L of LIGHTS) {
    let d = ((az - L.az + 540) % 360) - 180;
    const m = smooth(L.w, L.w * 0.55, Math.abs(d)) * smooth(L.h, L.h * 0.55, Math.abs(el - L.el));
    for (let i = 0; i < 3; i++) px[i] += L.k * L.c[i] * m;
  }
  return px;
}

function rgbe([r, g, b]) {
  const m = Math.max(r, g, b);
  if (m < 1e-32) return [0, 0, 0, 0];
  const e = Math.ceil(Math.log2(m)), scale = 256 / 2 ** e;
  return [Math.min(255, Math.floor(r * scale)), Math.min(255, Math.floor(g * scale)), Math.min(255, Math.floor(b * scale)), e + 128];
}

function rle(channel) {                               // Radiance "new" run-length packets for one channel of one scanline
  const out = [];
  for (let i = 0; i < channel.length;) {
    let run = 1;
    while (i + run < channel.length && run < 127 && channel[i + run] === channel[i]) run++;
    if (run >= 4) { out.push(128 + run, channel[i]); i += run; continue; }
    let lit = i, n = 0;
    while (lit < channel.length && n < 128) {
      let r2 = 1; while (lit + r2 < channel.length && channel[lit + r2] === channel[lit] && r2 < 4) r2++;
      if (r2 >= 4) break;
      lit++; n++;
    }
    if (n === 0) { lit = i + 1; n = 1; }
    out.push(n, ...channel.slice(i, i + n)); i += n;
  }
  return out;
}

const body = [];
for (let y = 0; y < H; y++) {
  const el = 90 - ((y + 0.5) / H) * 180;
  const row = Array.from({ length: W }, (_, x) => rgbe(radiance(((x + 0.5) / W) * 360 - 180, el)));
  body.push(2, 2, W >> 8, W & 255);
  for (let c = 0; c < 4; c++) body.push(...rle(row.map((p) => p[c])));
}
const header = Buffer.from(`#?RADIANCE\n# generated by tools/make-env.mjs\nFORMAT=32-bit_rle_rgbe\n\n-Y ${H} +X ${W}\n`, "latin1");
const out = join(dirname(fileURLToPath(import.meta.url)), "../assets/env/studio.hdr");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, Buffer.concat([header, Buffer.from(body)]));
console.log(`assets/env/studio.hdr  ${((header.length + body.length) / 1024).toFixed(1)} KB`);
